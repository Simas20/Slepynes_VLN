ZONES.contains = function (p, includeNaujamiestis) {
  return Object.values(ZONES.areas).some((area) => {
    if (area.optional && !includeNaujamiestis) return false;
    let inside = false;
    const poly = area.coords;
    for (let i = 0, j = poly.length - 1; i < poly.length; j = i++) {
      const [yi, xi] = poly[i], [yj, xj] = poly[j];
      if ((yi > p.lat) !== (yj > p.lat) && p.lng < ((xj - xi) * (p.lat - yi)) / (yj - yi) + xi) inside = !inside;
    }
    return inside;
  });
};

